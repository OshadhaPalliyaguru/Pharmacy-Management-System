package services.impl;

import javafx.collections.FXCollections;
import javafx.collections.ObservableList;
import model.dto.CartItem;
import model.dto.Medicine;
import model.dto.Sales;
import repository.MedicineRepository;
import repository.impl.MedicineRepositoryImpl;
import services.BillingService;
import services.MedicineService;
import services.SaleService;
import services.SalesItemService;

import java.sql.ResultSet;
import java.sql.SQLException;

public class BillingServiceImpl implements BillingService {

    // ✅ FIX: Initialize these services!
    private final MedicineService medicineService = new MedicineServiceImpl();
    private final MedicineRepository medicineRepository = new MedicineRepositoryImpl();
    private final SaleService saleService = new SalesServiceImpl();
    private final SalesItemService salesItemService = new SalesItemServiceImpl();

    @Override
    public ObservableList<Medicine> searchByName(String name) {
        ObservableList<Medicine> list = FXCollections.observableArrayList();
        try {
            ResultSet resultSet = medicineRepository.searchByName(name);
            while (resultSet.next()) { // Changed if -> while to get ALL results
                Medicine medicine = new Medicine(
                        resultSet.getInt("id"),
                        resultSet.getString("name"),
                        resultSet.getString("brand"),
                        resultSet.getString("batch_no"),
                        resultSet.getDate("expiry_date").toLocalDate(),
                        resultSet.getInt("quantity"),
                        resultSet.getDouble("unit_price"),
                        resultSet.getInt("reorder_level"),
                        resultSet.getTimestamp("created_at").toLocalDateTime(),
                        resultSet.getTimestamp("updated_at").toLocalDateTime()
                );
                list.add(medicine);
            }
        } catch (SQLException e) {
            throw new RuntimeException(e);
        }
        return list;
    }

    @Override
    public void billing(Sales sales, ObservableList<CartItem> cartItems) {
        // 1. Save the main Sale record
        int saleId = saleService.addSales(sales);
        if (saleId <= 0) return;

        // 2. Set the ID generated by the database
        sales.setId(saleId);

        // 3. Save the individual items (Medicines in that bill)
        salesItemService.addSaleItem(sales, cartItems);

        // 4. Reduce the stock from the inventory
        medicineService.updateMedicineQty(cartItems);
    }
}